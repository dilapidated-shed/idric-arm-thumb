_start:
        @ 24 Float32 observations = 96 bytes; remaining stack words are loop temporaries.
        sub     sp, sp, #112
        mov     r4, sp

        @ E5M3 is storage-only. These helpers decode operands to Float32,
        @ compute there, store the positive result back to E5M3, then decode
        @ that stored result for observation.
        movs    r0, #0x7c        @ nominal 1.5
        movs    r1, #0x70        @ nominal 0.5
        bl      e5m3_add_observe
        str     r0, [r4, #0]

        movs    r0, #0x7c
        movs    r1, #0x70
        bl      e5m3_sub_observe
        str     r0, [r4, #4]

        movs    r0, #0x7c
        movs    r1, #0x70
        bl      e5m3_mul_observe
        str     r0, [r4, #8]

        movs    r0, #0x7c
        movs    r1, #0x70
        bl      e5m3_div_observe
        str     r0, [r4, #12]

        movs    r0, #0x7c
        bl      e5m3_square_observe
        str     r0, [r4, #16]

        movs    r0, #0x7c
        bl      e5m3_cube_observe
        str     r0, [r4, #20]

        movs    r0, #0x80        @ nominal 2
        bl      e5m3_sqrt_observe
        str     r0, [r4, #24]

        @ Full recovered 14x26 Dakota measurement-model Jacobian.
        @ E5M3 has no sign and no distinguished zero, so nonzero magnitudes
        @ are E5M3 payloads while sign and structural-zero metadata remain
        @ separate. Multiplication and accumulation are Float32, as required
        @ for a storage-only format. Signed Jv results remain Float32.
        ldr     r5, =dakota_jacobian_e5m3
        ldr     r6, =dakota_jacobian_sign
        ldr     r7, =dakota_jacobian_zero
        add.w   r9, r4, #28
        movs    r8, #14
.Ljacobian_row:
        ldr     r10, =dakota_direction_e5m3
        ldr     r11, =dakota_direction_sign
        movs    r0, #26
        str     r0, [r4, #100]
        movs    r0, #0
        str     r0, [r4, #108]
.Ljacobian_column:
        ldrb    r0, [r7], #1
        cmp     r0, #0
        bne     .Ljacobian_zero

        ldrb    r0, [r5], #1
        bl      e5m3_to_f32_test
        str     r0, [r4, #104]

        ldrb    r0, [r10], #1
        bl      e5m3_to_f32_test
        vmov    s2, r0
        ldr     r0, [r4, #104]
        vmov    s1, r0
        vmul.f32 s1, s1, s2

        ldrb    r0, [r6], #1
        ldrb    r1, [r11], #1
        eors    r0, r1
        beq     .Ljacobian_positive
        vneg.f32 s1, s1
.Ljacobian_positive:
        ldr     r0, [r4, #108]
        vmov    s0, r0
        vadd.f32 s0, s0, s1
        vmov    r0, s0
        str     r0, [r4, #108]
        b       .Ljacobian_next

.Ljacobian_zero:
        add.w   r5, r5, #1
        add.w   r6, r6, #1
        add.w   r10, r10, #1
        add.w   r11, r11, #1

.Ljacobian_next:
        ldr     r0, [r4, #100]
        subs    r0, r0, #1
        str     r0, [r4, #100]
        bne     .Ljacobian_column

        ldr     r0, [r4, #108]
        str     r0, [r9], #4
        subs    r8, r8, #1
        bne     .Ljacobian_row

        @ Rotate (3,4) by one steering-wheel turn / 17.4.
        @ Stored inputs: cos -> 0x76, sin -> 0x6b, 3 -> 0x84, 4 -> 0x88.
        movs    r0, #0x76
        movs    r1, #0x6b
        movs    r2, #0x84
        movs    r3, #0x88
        bl      e5m3_rotate_x_observe
        str     r0, [r4, #84]

        movs    r0, #0x6b
        movs    r1, #0x76
        movs    r2, #0x84
        movs    r3, #0x88
        bl      e5m3_rotate_y_observe
        str     r0, [r4, #88]

        @ Caster from a 4-degree camber swing. The multiplier is stored as
        @ E5M3 0x7b; the positive product is stored again before observation.
        movs    r0, #0x88
        movs    r1, #0x7b
        bl      e5m3_mul_observe
        str     r0, [r4, #92]

        @ Emit raw Float32 observations. The host prints reference/observed/residual.
        movs    r0, #1
        mov     r1, r4
        movs    r2, #96
        movs    r7, #4
        svc     #0

        add     sp, sp, #112
        movs    r0, #0
        movs    r7, #1
        svc     #0

