        bl      e3m2_sqrt_test
        strb    r0, [r4, #6]

        @ Full recovered candidate measurement-model Jacobian from econometrician:
        @ 14 camber-observation rows x 26 named state/nuisance coordinates.
        @ The deterministic direction exercises every column; all values are exact E3M2.
        ldr     r5, =dakota_jacobian_e3m2
        add.w   r10, r4, #7
        movs    r8, #14
.Ljacobian_row:
        ldr     r6, =dakota_direction_e3m2
        movs    r7, #0
        movs    r9, #26
.Ljacobian_column:
        ldrb    r0, [r5], #1
        ldrb    r1, [r6], #1
        bl      e3m2_mul_test
        mov     r1, r7
        bl      e3m2_add_test
        mov     r7, r0
        subs    r9, r9, #1
        bne     .Ljacobian_column
        strb    r7, [r10], #1
        subs    r8, r8, #1
        bne     .Ljacobian_row

        @ Rotate (3,4) by one steering-wheel turn / 17.4.
        @ theta=20.689655 deg; cos(theta)->0.875 E3M2, sin(theta)->0.375 E3M2.
        movs    r0, #0x0b
        movs    r1, #0x06
        movs    r2, #0x12
        movs    r3, #0x14
        bl      e3m2_rotate_x_test
        strb    r0, [r4, #21]

        movs    r0, #0x06
        movs    r1, #0x0b
        movs    r2, #0x12
        movs    r3, #0x14
        bl      e3m2_rotate_y_test
        strb    r0, [r4, #22]

        @ Caster from a 4-degree camber swing:
        @ 4 * (1 / (2 sin(theta))); multiplier 1.415204... -> E3M2 1.5.
        movs    r0, #0x14
        movs    r1, #0x0e
        bl      e3m2_mul_test
        strb    r0, [r4, #23]

        @ Emit raw E3M2 payloads. The host observer prints reference/observed/residue.
        movs    r0, #1
        mov     r1, r4
        movs    r2, #24
        movs    r7, #4
        svc     #0

        add     sp, sp, #32
        movs    r0, #0
        movs    r7, #1
        svc     #0

